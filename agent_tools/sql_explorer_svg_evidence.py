"""Lossless export inputs and observational font probes for GitHub captures."""

from __future__ import annotations

import base64
import math
import platform
import re
import shutil
import struct
import subprocess
from importlib.metadata import PackageNotFoundError, version
from io import BytesIO
from tempfile import TemporaryFile
from typing import Any
from xml.etree import ElementTree as ET

from agent_tools.sql_explorer_render_diagnostics import digest

MAX_SVG_BYTES = 4 * 1024 * 1024
MAX_COMPARISON_PNG_BYTES = 4 * 1024 * 1024
COMPARISON_FONT = "DejaVu Sans Mono"
MAX_PROBE_BYTES = 16 * 1024
MAX_FONT_REQUESTS = 8
_VIEWBOX_COMPONENTS = 4
MAX_FONT_FAMILY_LENGTH = 512
PROBE_TIMEOUT = 3
RASTER_VIEWPORT = (1280, 800)
SUPERSAMPLE_FACTOR = 2


def _version(package: str) -> str:
    try:
        return version(package)
    except PackageNotFoundError:
        return "unavailable"


def _font_probe(arguments: list[str]) -> dict[str, Any]:
    """Bound process duration and retained output without changing renderer settings."""
    executable = shutil.which(arguments[0])
    result: dict[str, Any] = {"command": arguments, "executable": executable}
    if executable is None:
        return {**result, "status": "unavailable"}
    with TemporaryFile() as stdout, TemporaryFile() as stderr:
        try:
            completed = subprocess.run(
                [executable, *arguments[1:]],
                stdout=stdout,
                stderr=stderr,
                timeout=PROBE_TIMEOUT,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            result.update(status="unavailable", reason=type(exc).__name__)
        else:
            result.update(
                status="ok" if completed.returncode == 0 else "failed",
                returncode=completed.returncode,
            )
        for name, stream in (("stdout", stdout), ("stderr", stderr)):
            size = stream.tell()
            stream.seek(0)
            data = stream.read(MAX_PROBE_BYTES)
            result[name] = {
                "text": data.decode("utf-8", errors="replace"),
                "encoding": "UTF-8 with replacement for invalid probe bytes",
                "byte_length": size,
                "truncated": size > MAX_PROBE_BYTES,
            }
    return result


def _font_context(svg: str) -> dict[str, Any]:
    root = ET.fromstring(svg)  # noqa: S314 - generated by Textual, never owner input.
    requested = set()
    for node in root.iter():
        if node.get("font-family"):
            requested.add(node.attrib["font-family"])
        css = (node.text or "") if node.tag.rsplit("}", 1)[-1] == "style" else ""
        for declaration in (css, node.get("style", "")):
            requested.update(re.findall(r"font-family\s*:\s*([^;}]+)", declaration))
    families = sorted(value.strip() for value in requested)
    # Fontconfig results are system observations, not proof of resvg's chosen font.
    return {
        "requested_families": [
            family[:MAX_FONT_FAMILY_LENGTH] for family in families[:MAX_FONT_REQUESTS]
        ],
        "family_names_truncated": any(len(family) > MAX_FONT_FAMILY_LENGTH for family in families),
        "requested_family_count": len(families),
        "requests_truncated": len(families) > MAX_FONT_REQUESTS,
        "available_fonts": _font_probe(["fc-list", "--format=%{family}\t%{style}\t%{file}\n"]),
        "system_matches": [
            {
                "requested_family": family[:MAX_FONT_FAMILY_LENGTH],
                "probe": _font_probe(
                    ["fc-match", "--format=%{family}\t%{style}\t%{file}\n", "--", family]
                )
                if len(family) <= MAX_FONT_FAMILY_LENGTH
                else {"status": "unavailable", "reason": "font_family_length_limit"},
            }
            for family in families[:MAX_FONT_REQUESTS]
        ],
        "renderer_selection": {
            "status": "unobservable",
            "reason": "resvg-py svg_to_bytes exposes no selected-font diagnostic API",
        },
    }


def export_input_evidence(
    svg: str,
    framed_svg: str,
    png: bytes,
    *,
    rasterization: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Keep exact renderer inputs separate from the lossy parsed-diagnostic reducer."""
    inputs = {"raw_svg": svg.encode("utf-8"), "framed_svg": framed_svg.encode("utf-8")}
    if rasterization is not None:
        inputs["supersampling_svg"] = rasterization["svg"]["content"].encode("utf-8")
    total = sum(len(data) for data in inputs.values())
    complete = total <= MAX_SVG_BYTES
    records = {}
    for name, data in inputs.items():
        records[name] = {
            "encoding": "UTF-8",
            "byte_length": len(data),
            "sha256": digest(data),
        }
        if complete:
            records[name]["content"] = data.decode("utf-8")
    result: dict[str, Any] = {
        "schema_version": 1,
        "complete": complete,
        "missing": [] if complete else ["combined_svg_byte_limit"],
        "combined_svg_byte_length": total,
        "combined_svg_byte_limit": MAX_SVG_BYTES,
        "content_encoding": "JSON strings; encode decoded content as UTF-8 without normalization",
        "inputs": records,
        "png_sha256": digest(png),
        "versions": {
            "python": platform.python_version(),
            **{package: _version(package) for package in ("textual", "rich", "resvg-py")},
        },
        "fonts": _font_context(svg),
    }
    if rasterization is not None:
        result["rasterization"] = {
            key: value for key, value in rasterization.items() if key != "svg"
        }
        result["rasterization"]["svg_input"] = "inputs.supersampling_svg"
    return result


def _comparison_font() -> dict[str, Any]:
    """Verify an exact installed family, rejecting fontconfig fallback observations."""
    probe = _font_probe(["fc-match", "--format=%{family}\t%{file}\n", "--", COMPARISON_FONT])
    output = probe.get("stdout", {})
    rows = output.get("text", "").strip().splitlines()
    family, separator, path = rows[0].partition("\t") if len(rows) == 1 else ("", "", "")
    available = (
        probe["status"] == "ok"
        and not output.get("truncated", False)
        and bool(separator and path)
        and COMPARISON_FONT.casefold() in {name.strip().casefold() for name in family.split(",")}
    )
    return {
        "family": COMPARISON_FONT,
        "available": available,
        "probe": probe,
        "renderer_selection": "unobservable; installed-family observation only",
    }


def _terminal_font_variant(svg: str) -> str:
    """Change one generated matrix declaration without XML reserialization."""
    candidates = []
    for style in re.finditer(r"<(?:\w+:)?style\b[^>]*>(.*?)</(?:\w+:)?style\s*>", svg, re.DOTALL):
        candidates.extend(
            (style, block)
            for block in re.finditer(r"([^{}]+)\{([^{}]*)\}", style[1])
            if re.search(r"\.terminal-[\w-]+-matrix\b", block[1])
        )
    if len(candidates) != 1:
        message = "missing_or_ambiguous_terminal_matrix"
        raise ValueError(message)
    style, block = candidates[0]
    if re.fullmatch(r"\s*\.terminal-[0-9]+-matrix\s*", block[1]) is None:
        message = "unsupported_terminal_matrix_selector"
        raise ValueError(message)
    declarations = list(re.finditer(r"(?:^|;)\s*font-family\s*:\s*([^;{}]+)", block[2]))
    if len(declarations) != 1:
        message = "missing_or_ambiguous_terminal_font"
        raise ValueError(message)
    declaration = declarations[0]
    start = style.start(1) + block.start(2) + declaration.start(1)
    end = style.start(1) + block.start(2) + declaration.end(1)
    return svg[:start] + "'" + COMPARISON_FONT + "', monospace" + svg[end:]


def _render_svg(svg: str) -> bytes:
    import resvg_py  # noqa: PLC0415 - optional GitHub capture dependency.

    return bytes(resvg_py.svg_to_bytes(svg_string=svg))


def _png_dimensions(png: bytes) -> list[int]:
    header = struct.Struct(">8sI4sII")
    if len(png) < header.size:
        message = "invalid_png_header"
        raise ValueError(message)
    signature, _length, kind, width, height = header.unpack_from(png)
    if signature != b"\x89PNG\r\n\x1a\n" or kind != b"IHDR":
        message = "invalid_png_header"
        raise ValueError(message)
    if not width or not height:
        message = "invalid_png_dimensions"
        raise ValueError(message)
    return [width, height]


def supersampling_svg(framed_svg: str) -> str:
    """Scale the complete, unchanged target frame through one outer viewport."""
    width, height = RASTER_VIEWPORT
    return (
        '<svg xmlns="http://www.w3.org/2000/svg"'
        f' width="{width * SUPERSAMPLE_FACTOR}" height="{height * SUPERSAMPLE_FACTOR}"'
        f' viewBox="0 0 {width} {height}">' + framed_svg + "</svg>"
    )


def rasterize_framed_svg(framed_svg: str) -> tuple[bytes, dict[str, Any]]:
    """Render at twice the target size, then perform exactly one Lanczos reduction."""
    from PIL import Image  # noqa: PLC0415 - optional agent capture dependency.

    svg = supersampling_svg(framed_svg)
    intermediate = _render_svg(svg)
    dimensions = _png_dimensions(intermediate)
    expected = [size * SUPERSAMPLE_FACTOR for size in RASTER_VIEWPORT]
    if dimensions != expected:
        message = f"unexpected_supersampling_dimensions: {dimensions}"
        raise ValueError(message)
    with Image.open(BytesIO(intermediate)) as image:
        reduced = image.resize(RASTER_VIEWPORT, resample=Image.Resampling.LANCZOS)
        with reduced, BytesIO() as output:
            reduced.save(output, format="PNG")
            png = output.getvalue()
    final_dimensions = _png_dimensions(png)
    if final_dimensions != list(RASTER_VIEWPORT):
        message = f"unexpected_final_dimensions: {final_dimensions}"
        raise ValueError(message)
    encoded = svg.encode("utf-8")
    return png, {
        "svg": {
            "encoding": "UTF-8",
            "byte_length": len(encoded),
            "sha256": digest(encoded),
            "content": svg,
        },
        "renderer": "resvg_py.svg_to_bytes",
        "renderer_arguments": {"input": "svg.content", "other_arguments": {}},
        "processing": {
            "scale_factor": SUPERSAMPLE_FACTOR,
            "intermediate": {"dimensions": dimensions, "sha256": digest(intermediate)},
            "final": {"dimensions": final_dimensions, "sha256": digest(png)},
            "pillow_version": _version("Pillow"),
            "reduction_filter": "Image.Resampling.LANCZOS",
            "reductions": 1,
        },
    }


def _comparison_inputs(svg: str, framed_svg: str, font: dict[str, Any]) -> dict[str, Any]:
    variants: dict[str, Any] = {}
    for framing, original in (("raw", svg), ("framed", framed_svg)):
        for family in ("original", "dejavu"):
            record: dict[str, Any] = {
                "framing": framing,
                "font": "original declarations" if family == "original" else COMPARISON_FONT,
                "renderer": "resvg_py.svg_to_bytes",
                "renderer_arguments": {"input": "svg.content", "other_arguments": {}},
                "sizing": "native SVG sizing" if framing == "raw" else "existing framed SVG sizing",
                "status": "pending",
            }
            variants[framing + "_" + family] = record
            if family == "dejavu" and not font["available"]:
                record.update(status="omitted", reason="comparison_font_unavailable")
                continue
            try:
                content = original if family == "original" else _terminal_font_variant(original)
            except ValueError as exc:
                record.update(status="omitted", reason=str(exc))
                continue
            encoded = content.encode("utf-8")
            record["svg"] = {
                "encoding": "UTF-8",
                "byte_length": len(encoded),
                "sha256": digest(encoded),
                "content": content,
            }
    return variants


def _native_dimensions(svg: str) -> tuple[str, str]:
    root = ET.fromstring(svg)  # noqa: S314 - generated capture input.
    values = root.get("viewBox", "").replace(",", " ").split()
    if len(values) != _VIEWBOX_COMPONENTS:
        message = "missing_or_invalid_native_viewbox"
        raise ValueError(message)
    if any(not math.isfinite(float(value)) for value in values) or any(
        float(value) <= 0 for value in values[2:]
    ):
        message = "missing_or_invalid_native_viewbox"
        raise ValueError(message)
    return values[2], values[3]


def _preserved_frame(svg: str, width: str, height: str) -> str:
    """Alter the root sizing declaration only; retain every interior byte."""
    opening = re.search(r"""<svg\b(?:[^>"']|"[^"]*"|'[^']*')*>""", svg)
    if opening is None or opening[0].endswith("/>"):
        message = "unsupported_original_svg_root"
        raise ValueError(message)
    # A declaration is legal before the root, never inside the enclosing frame.
    prefix = re.sub(r"<\?xml\b.*?\?>", "", svg[: opening.start()], flags=re.DOTALL)
    if prefix.strip():
        message = "unsupported_original_svg_prolog"
        raise ValueError(message)
    attributes = {"width": width, "height": height, "preserveAspectRatio": "xMidYMid meet"}
    tag = opening[0]
    for name, value in attributes.items():
        pattern = rf"""(\s{name}\s*=\s*)(["'])(.*?)\2"""
        tag, count = re.subn(
            pattern,
            lambda match, replacement=value: match[1] + match[2] + replacement + match[2],
            tag,
        )
        if not count:
            tag = tag[:-1] + f' {name}="{value}">'
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}">'
        '<rect width="100%" height="100%" fill="#0d1117"/>' + tag + svg[opening.end() :] + "</svg>"
    )


def _framing_control(svg: str, framed_svg: str, identity: str) -> str:
    """Separate XML serialization from target scaling without changing capture."""
    if identity == "raw_xml_native":
        root = ET.fromstring(svg)  # noqa: S314 - generated capture input.
        return ET.tostring(root, encoding="unicode")
    if identity == "framed_preserved_target":
        frame = ET.fromstring(framed_svg)  # noqa: S314 - generated capture input.
        return _preserved_frame(svg, frame.attrib["width"], frame.attrib["height"])
    width, height = _native_dimensions(svg)
    frame = ET.fromstring(framed_svg)  # noqa: S314 - generated capture input.
    screens = [child for child in frame if child.tag.rsplit("}", 1)[-1] == "svg"]
    if len(screens) != 1:
        message = "missing_or_ambiguous_framed_screen"
        raise ValueError(message)
    for root in (frame, screens[0]):
        root.set("width", width)
        root.set("height", height)
    return ET.tostring(frame, encoding="unicode")


def _add_framing_controls(variants: dict[str, Any], svg: str, framed_svg: str) -> None:
    for identity, sizing in (
        ("raw_xml_native", "original native SVG sizing; XML reserialization only"),
        ("framed_preserved_target", "existing target frame sizing; original interior bytes"),
        ("framed_xml_native", "XML frame at original viewBox dimensions"),
    ):
        record: dict[str, Any] = {
            "framing": identity,
            "font": "original declarations",
            "renderer": "resvg_py.svg_to_bytes",
            "renderer_arguments": {"input": "svg.content", "other_arguments": {}},
            "sizing": sizing,
            "status": "pending",
        }
        variants[identity] = record
        try:
            content = _framing_control(svg, framed_svg, identity)
        except (ET.ParseError, KeyError, ValueError) as exc:
            record.update(status="omitted", reason=type(exc).__name__ + ": " + str(exc)[:256])
            continue
        encoded = content.encode("utf-8")
        record["svg"] = {
            "encoding": "UTF-8",
            "byte_length": len(encoded),
            "sha256": digest(encoded),
            "content": content,
        }


def _comparison_pngs(variants: dict[str, Any], ordinary_png: bytes) -> int:
    total = 0
    for identity, record in variants.items():
        if record["status"] != "pending":
            continue
        try:
            png = (
                ordinary_png
                if identity == "framed_supersampled"
                else _render_svg(record["svg"]["content"])
            )
            dimensions = _png_dimensions(png)
        except Exception as exc:  # noqa: BLE001 - retain renderer failures as incomplete evidence.
            record.update(status="failed", reason=type(exc).__name__ + ": " + str(exc)[:256])
            continue
        total += len(png)
        record["png"] = {
            "encoding": "base64",
            "byte_length": len(png),
            "sha256": digest(png),
            "dimensions": dimensions,
            "reused_ordinary_png": identity == "framed_supersampled",
            "content": base64.b64encode(png).decode("ascii"),
        }
        record["status"] = "ok"
    return total


def rasterization_comparisons(
    svg: str,
    framed_svg: str,
    png: bytes,
    *,
    rasterization: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Bound lossless comparisons; incompleteness never establishes a cause."""
    font = _comparison_font()
    variants = _comparison_inputs(svg, framed_svg, font)
    _add_framing_controls(variants, svg, framed_svg)
    if rasterization is not None:
        variants["framed_supersampled"] = {
            **rasterization,
            "svg": dict(rasterization["svg"]),
            "framing": "unchanged target frame in doubled outer viewport",
            "font": "original declarations",
            "sizing": "2560x1600 render; one Lanczos reduction to 1280x800",
            "status": "pending",
        }
    svg_total = sum(record.get("svg", {}).get("byte_length", 0) for record in variants.values())
    missing = []
    png_total = 0
    if svg_total > MAX_SVG_BYTES:
        missing.append("combined_svg_byte_limit")
        for record in variants.values():
            if "svg" in record:
                record["svg"].pop("content")
                record.update(status="omitted", reason="combined_svg_byte_limit")
    else:
        png_total = _comparison_pngs(variants, png)
    if png_total > MAX_COMPARISON_PNG_BYTES:
        missing.append("combined_png_byte_limit")
        for record in variants.values():
            if "png" in record:
                record["png"].pop("content")
                record.update(status="omitted", reason="combined_png_byte_limit")
    missing.extend(
        identity + ":" + record["reason"]
        for identity, record in variants.items()
        if record["status"] != "ok"
    )
    return {
        "schema_version": 1,
        "complete": not missing,
        "missing": missing,
        "combined_svg_byte_length": svg_total,
        "combined_svg_byte_limit": MAX_SVG_BYTES,
        "combined_png_byte_length": png_total,
        "combined_png_byte_limit": MAX_COMPARISON_PNG_BYTES,
        "content_encoding": "UTF-8 JSON SVG strings without normalization; base64 PNG bytes",
        "ordinary_png_sha256": digest(png),
        "versions": {
            "python": platform.python_version(),
            **{package: _version(package) for package in ("textual", "rich", "resvg-py")},
        },
        "comparison_font": font,
        "variants": variants,
    }
