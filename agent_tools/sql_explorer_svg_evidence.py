"""Lossless export inputs and observational font probes for GitHub captures."""

from __future__ import annotations

import base64
import platform
import re
import shutil
import struct
import subprocess
from importlib.metadata import PackageNotFoundError, version
from tempfile import TemporaryFile
from typing import Any
from xml.etree import ElementTree as ET

from agent_tools.sql_explorer_render_diagnostics import digest

MAX_SVG_BYTES = 4 * 1024 * 1024
MAX_COMPARISON_PNG_BYTES = 4 * 1024 * 1024
COMPARISON_FONT = "DejaVu Sans Mono"
MAX_PROBE_BYTES = 16 * 1024
MAX_FONT_REQUESTS = 8
PROBE_TIMEOUT = 3


def _version(package: str) -> str:
    try:
        return version(package)
    except PackageNotFoundError:
        return "unavailable"


def _font_probe(arguments: list[str]) -> dict[str, Any]:
    """Bound process duration and retained output without changing renderer settings."""
    executable = shutil.which(arguments[0])
    result: dict[str, Any] = {"command": arguments, "executable": executable}
    if executable is None:
        return {**result, "status": "unavailable"}
    with TemporaryFile() as stdout, TemporaryFile() as stderr:
        try:
            completed = subprocess.run(  # noqa: S603 - fixed fontconfig probes, no shell.
                [executable, *arguments[1:]],
                stdout=stdout,
                stderr=stderr,
                timeout=PROBE_TIMEOUT,
                check=False,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            result.update(status="unavailable", reason=type(exc).__name__)
        else:
            result.update(
                status="ok" if completed.returncode == 0 else "failed",
                returncode=completed.returncode,
            )
        for name, stream in (("stdout", stdout), ("stderr", stderr)):
            size = stream.tell()
            stream.seek(0)
            data = stream.read(MAX_PROBE_BYTES)
            result[name] = {
                "text": data.decode("utf-8", errors="replace"),
                "encoding": "UTF-8 with replacement for invalid probe bytes",
                "byte_length": size,
                "truncated": size > MAX_PROBE_BYTES,
            }
    return result


def _font_context(svg: str) -> dict[str, Any]:
    root = ET.fromstring(svg)  # noqa: S314 - generated by Textual, never owner input.
    requested = set()
    for node in root.iter():
        if node.get("font-family"):
            requested.add(node.attrib["font-family"])
        css = (node.text or "") if node.tag.rsplit("}", 1)[-1] == "style" else ""
        for declaration in (css, node.get("style", "")):
            requested.update(re.findall(r"font-family\s*:\s*([^;}]+)", declaration))
    families = sorted(value.strip() for value in requested)
    # Fontconfig results are system observations, not proof of resvg's chosen font.
    return {
        "requested_families": [family[:512] for family in families[:MAX_FONT_REQUESTS]],
        "family_names_truncated": any(len(family) > 512 for family in families),
        "requested_family_count": len(families),
        "requests_truncated": len(families) > MAX_FONT_REQUESTS,
        "available_fonts": _font_probe(["fc-list", "--format=%{family}\t%{style}\t%{file}\n"]),
        "system_matches": [
            {
                "requested_family": family[:512],
                "probe": _font_probe(
                    ["fc-match", "--format=%{family}\t%{style}\t%{file}\n", "--", family]
                )
                if len(family) <= 512
                else {"status": "unavailable", "reason": "font_family_length_limit"},
            }
            for family in families[:MAX_FONT_REQUESTS]
        ],
        "renderer_selection": {
            "status": "unobservable",
            "reason": "resvg-py svg_to_bytes exposes no selected-font diagnostic API",
        },
    }


def export_input_evidence(svg: str, framed_svg: str, png: bytes) -> dict[str, Any]:
    """Keep exact renderer inputs separate from the lossy parsed-diagnostic reducer."""
    inputs = {"raw_svg": svg.encode("utf-8"), "framed_svg": framed_svg.encode("utf-8")}
    total = sum(len(data) for data in inputs.values())
    complete = total <= MAX_SVG_BYTES
    records = {}
    for name, data in inputs.items():
        records[name] = {
            "encoding": "UTF-8",
            "byte_length": len(data),
            "sha256": digest(data),
        }
        if complete:
            records[name]["content"] = data.decode("utf-8")
    return {
        "schema_version": 1,
        "complete": complete,
        "missing": [] if complete else ["combined_svg_byte_limit"],
        "combined_svg_byte_length": total,
        "combined_svg_byte_limit": MAX_SVG_BYTES,
        "content_encoding": "JSON strings; encode decoded content as UTF-8 without normalization",
        "inputs": records,
        "png_sha256": digest(png),
        "versions": {
            "python": platform.python_version(),
            **{package: _version(package) for package in ("textual", "rich", "resvg-py")},
        },
        "fonts": _font_context(svg),
    }


def _comparison_font() -> dict[str, Any]:
    """Verify an exact installed family, rejecting fontconfig fallback observations."""
    probe = _font_probe(["fc-match", "--format=%{family}\t%{file}\n", "--", COMPARISON_FONT])
    output = probe.get("stdout", {})
    rows = output.get("text", "").strip().splitlines()
    family, separator, path = rows[0].partition("\t") if len(rows) == 1 else ("", "", "")
    available = (
        probe["status"] == "ok"
        and not output.get("truncated", False)
        and bool(separator and path)
        and COMPARISON_FONT.casefold() in {name.strip().casefold() for name in family.split(",")}
    )
    return {
        "family": COMPARISON_FONT,
        "available": available,
        "probe": probe,
        "renderer_selection": "unobservable; installed-family observation only",
    }


def _terminal_font_variant(svg: str) -> str:
    """Change one generated matrix declaration without XML reserialization."""
    candidates = []
    for style in re.finditer(r"<(?:\w+:)?style\b[^>]*>(.*?)</(?:\w+:)?style\s*>", svg, re.S):
        for block in re.finditer(r"([^{}]+)\{([^{}]*)\}", style[1]):
            if re.search(r"\.terminal-[\w-]+-matrix\b", block[1]):
                candidates.append((style, block))
    if len(candidates) != 1:
        message = "missing_or_ambiguous_terminal_matrix"
        raise ValueError(message)
    style, block = candidates[0]
    if re.fullmatch(r"\s*\.terminal-[0-9]+-matrix\s*", block[1]) is None:
        message = "unsupported_terminal_matrix_selector"
        raise ValueError(message)
    declarations = list(re.finditer(r"(?:^|;)\s*font-family\s*:\s*([^;{}]+)", block[2]))
    if len(declarations) != 1:
        message = "missing_or_ambiguous_terminal_font"
        raise ValueError(message)
    declaration = declarations[0]
    start = style.start(1) + block.start(2) + declaration.start(1)
    end = style.start(1) + block.start(2) + declaration.end(1)
    return svg[:start] + "'" + COMPARISON_FONT + "', monospace" + svg[end:]


def _render_svg(svg: str) -> bytes:
    import resvg_py  # noqa: PLC0415 - optional GitHub capture dependency.

    return bytes(resvg_py.svg_to_bytes(svg_string=svg))


def _png_dimensions(png: bytes) -> list[int]:
    header = struct.Struct(">8sI4sII")
    if len(png) < header.size:
        message = "invalid_png_header"
        raise ValueError(message)
    signature, _length, kind, width, height = header.unpack_from(png)
    if signature != b"\x89PNG\r\n\x1a\n" or kind != b"IHDR":
        message = "invalid_png_header"
        raise ValueError(message)
    if not width or not height:
        message = "invalid_png_dimensions"
        raise ValueError(message)
    return [width, height]


def _comparison_inputs(svg: str, framed_svg: str, font: dict[str, Any]) -> dict[str, Any]:
    variants: dict[str, Any] = {}
    for framing, original in (("raw", svg), ("framed", framed_svg)):
        for family in ("original", "dejavu"):
            record: dict[str, Any] = {
                "framing": framing,
                "font": "original declarations" if family == "original" else COMPARISON_FONT,
                "renderer": "resvg_py.svg_to_bytes",
                "renderer_arguments": {"input": "svg.content", "other_arguments": {}},
                "sizing": "native SVG sizing" if framing == "raw" else "existing framed SVG sizing",
                "status": "pending",
            }
            variants[framing + "_" + family] = record
            if family == "dejavu" and not font["available"]:
                record.update(status="omitted", reason="comparison_font_unavailable")
                continue
            try:
                content = original if family == "original" else _terminal_font_variant(original)
            except ValueError as exc:
                record.update(status="omitted", reason=str(exc))
                continue
            encoded = content.encode("utf-8")
            record["svg"] = {
                "encoding": "UTF-8",
                "byte_length": len(encoded),
                "sha256": digest(encoded),
                "content": content,
            }
    return variants


def _comparison_pngs(variants: dict[str, Any], ordinary_png: bytes) -> int:
    total = 0
    for identity, record in variants.items():
        if record["status"] != "pending":
            continue
        try:
            png = (
                ordinary_png
                if identity == "framed_original"
                else _render_svg(record["svg"]["content"])
            )
            dimensions = _png_dimensions(png)
        except Exception as exc:  # noqa: BLE001 - retain failed diagnostics, never approve them.
            record.update(status="failed", reason=type(exc).__name__ + ": " + str(exc)[:256])
            continue
        total += len(png)
        record["png"] = {
            "encoding": "base64",
            "byte_length": len(png),
            "sha256": digest(png),
            "dimensions": dimensions,
            "reused_ordinary_png": identity == "framed_original",
            "content": base64.b64encode(png).decode("ascii"),
        }
        record["status"] = "ok"
    return total


def rasterization_comparisons(svg: str, framed_svg: str, png: bytes) -> dict[str, Any]:
    """Bound lossless four-way evidence; incompleteness never establishes a cause."""
    font = _comparison_font()
    variants = _comparison_inputs(svg, framed_svg, font)
    svg_total = sum(record.get("svg", {}).get("byte_length", 0) for record in variants.values())
    missing = []
    png_total = 0
    if svg_total > MAX_SVG_BYTES:
        missing.append("combined_svg_byte_limit")
        for record in variants.values():
            if "svg" in record:
                record["svg"].pop("content")
                record.update(status="omitted", reason="combined_svg_byte_limit")
    else:
        png_total = _comparison_pngs(variants, png)
    if png_total > MAX_COMPARISON_PNG_BYTES:
        missing.append("combined_png_byte_limit")
        for record in variants.values():
            if "png" in record:
                record["png"].pop("content")
                record.update(status="omitted", reason="combined_png_byte_limit")
    missing.extend(
        identity + ":" + record["reason"]
        for identity, record in variants.items()
        if record["status"] != "ok"
    )
    return {
        "schema_version": 1,
        "complete": not missing,
        "missing": missing,
        "combined_svg_byte_length": svg_total,
        "combined_svg_byte_limit": MAX_SVG_BYTES,
        "combined_png_byte_length": png_total,
        "combined_png_byte_limit": MAX_COMPARISON_PNG_BYTES,
        "content_encoding": "UTF-8 JSON SVG strings without normalization; base64 PNG bytes",
        "ordinary_png_sha256": digest(png),
        "versions": {
            "python": platform.python_version(),
            **{package: _version(package) for package in ("textual", "rich", "resvg-py")},
        },
        "comparison_font": font,
        "variants": variants,
    }
